-- | Emit compiles (already normalized) Join IR to Zig source text.
--
-- Every compiled unit — a top-level definition, a lifted @Lambda@ body, a
-- lifted (escaping) join consumer, a lifted @Object@ field, or a lifted
-- @Cocase@ branch — becomes an independent Zig function with the uniform
-- signature @fn (cap: []const rt.Value, args: []const rt.Value) rt.Value@.
-- Captures and parameters are bound to ordinary @const@s at function entry;
-- the function body ends with exactly one @return@ per control-flow path.
--
-- A @Join name consumer stmt@ binding is either:
--
--   * 'Malgo.Backend.Zig.ClosureConv.Local' — never lifted. No Zig code is
--     emitted for the binding itself; instead @consumer@'s AST is recorded
--     in the (plain, explicitly threaded) local environment, and every
--     @Cut@\/@Primitive@ site that targets @name@ inlines @consumer@'s logic
--     applied to the computed value, in place. This is always sound because
--     'Malgo.Backend.Zig.ClosureConv.escapingNamesStatement' guarantees such
--     uses never leave the current function.
--   * 'Malgo.Backend.Zig.ClosureConv.Escaping' — lifted into its own
--     function (capturing its free variables), allocated once as a real
--     @rt.Closure@ Value bound to an ordinary Zig @const@, and invoked
--     through @rt.applyCovalue@ wherever it is used.
module Malgo.Backend.Zig.Emit (compileToZig, mangleId) where

